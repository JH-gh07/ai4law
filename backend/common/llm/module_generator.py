def generate_chapter(
    llm_client: "LLMClient",
    module: str,
    chapter_title: str,
    context_block: str,
    citations: list[str] | None = None,
    citation_marker_section: str = "",
    use_citation_markers: bool = False,
    citation_registry: "CitationRegistry | None" = None,
) -> str:
    """用LLM生成一个章节的内容。

    Args:
        llm_client: LLMClient实例
        module: 模块标识符，如 'scc', 'dpia' 等
        chapter_title: 章节标题
        context_block: 包含企业信息和法规摘要的上下文文本块
    """
    system_prompt = SYSTEM_PROMPTS.get(module, "你是一名资深数据合规律师，请用专业中文撰写合规报告章节。")
    instruction = CHAPTER_INSTRUCTIONS.get(module, {}).get(chapter_title, f"请撰写「{chapter_title}」章节内容，内容专业、结构清晰。")

    prompt_context = context_block
    if use_citation_markers and citation_marker_section:
        prompt_context = f"{context_block}\n\n【可引用法规依据】\n{citation_marker_section}"

    prompt_constraint = STRICT_CONSTRAINT
    if use_citation_markers:
        prompt_constraint = (
            "写作约束：仅使用上下文提供的事实与法规参考，不得新增行业、国家/地区、主体、规模、"
            "交易/处理场景等信息。若上下文缺失，请写“未提供”。如需推测，请明确标注【推测】。"
            "所有标题、子标题、编号项都必须单独成行，严禁将“第一章/一、/（一）/1.”与正文连写在同一段中。"
            "如涉及分层结构，优先使用 Markdown 形式输出：章标题用“# ”，节标题用“## ”，小节用“### ”，清单项用“1.”或“-”。"
            "\n\n引用约束（必须遵守）："
            "\n- 下方【可引用法规依据】提供了可用依据，每条格式为 {{CIT-xxx}} = 法规名 条文"
            "\n- 需要引用法规时，在句末使用 {{CIT-xxx}} 标记"
            "\n- 禁止使用其他引用格式，禁止编造未提供的法规依据"
            "\n- 一个观点可引用多条：{{CIT-xxx}}{{CIT-yyy}}"
            "\n- 若无可引用依据，不要编造引用。"
        )

    user_prompt = (
        f"{instruction}\n\n"
        f"{prompt_context}\n\n"
        f"{prompt_constraint}\n\n"
        "请直接输出章节正文，格式为结构化段落，无需重复章节标题。字数在300-600字之间。"
    )
    raw = llm_client.chat(
        system=system_prompt,
        user=user_prompt,
        temperature=0.2,
        max_tokens=800,
    )
    # 剥离 LLM 输出的 markdown 内联格式（**粗体**, `代码` 等）
    # DOCX 渲染器不处理 markdown → 保留会变成字面 ** 和 _
    cleaned = strip_markdown_inline(raw)
    return apply_citation_pipeline(
        cleaned,
        registry=citation_registry,
        allowed_citations=citations,
    ).text
